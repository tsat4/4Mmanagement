create schema if not exists archive;
create table public.audit_log (id bigint generated always as identity primary key, table_name text, row_pk text, action text,
  actor text, actor_uid uuid, changed_fields text[], old_data jsonb, new_data jsonb, changed_at timestamptz default now());
create index idx_audit_log_changed_at on public.audit_log(changed_at);
create index idx_audit_log_table_row on public.audit_log(table_name, row_pk);
alter table public.audit_log enable row level security;
create policy audit_log_read on public.audit_log for select to authenticated using (true);
grant select, insert on public.audit_log to anon, authenticated;

create function public.fn_set_updated_at() returns trigger language plpgsql as $$ begin new.updated_at := now(); return new; end $$;
create function public.norm_person_name(s text) returns text language sql immutable as $$ select lower(btrim(s)) $$;
create function public.esm_schema_overview() returns int language sql as $$ select 1 $$;
create function public.esm_schema_table(p_table text) returns text language sql as $$ select p_table $$;
-- fn_audit ของ Main: ชื่อคนจาก auth.uid() → profiles
create function public.fn_audit() returns trigger language plpgsql security definer set search_path to 'public' as $$
declare v_uid uuid; v_actor text; begin
  v_uid := auth.uid();
  select full_name into v_actor from public.profiles where id = v_uid;
  insert into public.audit_log(table_name,row_pk,action,actor,actor_uid,new_data)
  values (TG_TABLE_NAME, to_jsonb(NEW)->>'id', TG_OP, coalesce(v_actor,'main-system'), v_uid, to_jsonb(NEW));
  return NEW; end $$;

create table public.profiles (id uuid primary key references auth.users(id), full_name text, role text);
create table public.notifications (id bigint generated by default as identity primary key, user_id uuid references auth.users(id), title text, created_at timestamptz default now());
create index idx_notifications_created on public.notifications(created_at);
create table public.employees (id serial primary key, name text, updated_at timestamptz);
create trigger trg_emp_upd before update on public.employees for each row execute function public.fn_set_updated_at();
create trigger trg_emp_audit after insert or update on public.employees for each row execute function public.fn_audit();
alter table public.employees enable row level security;
