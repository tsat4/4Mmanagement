/* ══ 🚩 ติ๊ก NG ต้องมีเหตุผล — กฎที่เดียวของทุกระบบตรวจเครื่อง (AM/PM) ══  2026-11-19
   คำสั่ง user: *"ทุกระบบการตรวจเครื่องจักรทั้ง am/pm ในกรณีที่เลือก NG ต้องใส่เหตุผลด้วย
   เพราะเกิดการกดผิดและพนักงานไม่รู้ตัว · แต่งานที่ตรวจครั้งก่อนว่า NG และเปิด MO แล้ว
   จะใช้การปิด MO ซ่อมแล้ว / แก้ไขเบื้องต้นแล้ว เป็นตัวดึงเหตุผลเก่า"*
   เคาะเพิ่ม 19/11: **"แก้ไขเบื้องต้นแล้ว" ให้ยกเหตุผลต่อ** (ของยังไม่มา ปัญหายังอยู่)
   \+ **เอาตัวเตือนตอนติ๊ก OK ทั้งที่ MO ยังไม่ซ่อมด้วย**

   ── ที่มา (วัดจริง 19/11 · 90 วัน) ────────────────────────────────────────────
   ผลตรวจ NG **43 จุด** · มีเหตุผลกำกับแค่ **8 จุด** ⇒ **81% ไม่มีเหตุผลเลย**
   และช่องเก็บเหตุผลรายจุด (`inspection_results.action_text`) **มีอยู่แล้ว** แต่ถูกใช้ **1 จาก 43**
   (Poka-Yoke ไม่ใช่ปัญหา — fail 2 ครั้ง มีเหตุผลครบทั้ง 2)

   ── 🔴 กฎของไฟล์นี้ ───────────────────────────────────────────────────────────
   1. **บังคับเฉพาะ "จุดที่คนกดเลือก NG"** — จุดที่วัดค่าแล้วหลุดสเปค ตัวเลขคือคำอธิบายอยู่แล้ว
      (เหตุผลของกฎนี้คือ "กดผิด" ซึ่งเกิดกับปุ่ม ไม่ใช่กับช่องกรอกตัวเลข)
   2. 🔴 **ทางลัดที่ถูกต้องต้องมี** — ถ้าบังคับพิมพ์ทุกกะบนเครื่องที่เสียค้างอยู่ คนจะพิมพ์ "." หรือ "เดิม"
      แล้วช่องนั้นกลายเป็นขยะเหมือนเดิม ⇒ ยกเหตุผลเก่ามาให้ **แต่ต้องกดยืนยัน**
   3. 🔴 **ยกมาต้องเห็นว่ายกมา ห้ามเติมเงียบ** — เติมเงียบ = คนกดผิดจะได้เหตุผลติดมาเอง
      ดูเหมือนตั้งใจ **แย่กว่าไม่มีเหตุผล** (แพ้ทางปัญหาที่ user ตั้งใจแก้)
   4. 🔴 **ยกเฉพาะ "จุดตรวจเดิม" ห้ามยกทั้งเครื่อง** — เครื่องหนึ่งมีหลายจุด
      MO ที่เปิดเรื่องจุด A ห้ามไปอธิบาย NG ของจุด B
   5. 🔴 **หยุดยกเมื่องานจบ** — MO ปิด/ยกเลิก หรือช่างประกาศว่าเครื่อง "ใช้ได้" (`usability='ok'`)
      ⇒ NG รอบใหม่หลังจากนั้น = ปัญหาใหม่ ต้องอธิบายใหม่
      **ยกเว้น "ใช้ได้ชั่วคราว" (`temp`) — ยกต่อ** แต่เปลี่ยนข้อความให้ตรงความจริง (คำสั่ง user 19/11)
   6. 🔴 **ติ๊ก OK ทั้งที่ MO ยังซ่อมไม่เสร็จ = เตือน ไม่บล็อก** — บางทีช่างเพิ่งแก้เสร็จจริงแต่ยังไม่ปิดใบ
      (บล็อก = ไลน์ตรวจไม่ผ่านเพราะเอกสาร · กฎเดิมของโมดูล "ห้ามให้เอกสารหยุดงานหน้าไลน์")  */
import { isMoOpen } from './mtnStepPerm.js';

const txt = (v) => String(v ?? '').trim();

/** ใบ MO นี้ "ยังไม่ซ่อมเสร็จ" ไหม — ใช้ตัดสินทั้งการยกเหตุผลและการเตือนตอนติ๊ก OK */
export const moUnresolved = (mo) => !!mo && isMoOpen(mo) && !mo.repair_done_at;

/**
 * ยกเหตุผลเก่ามาใช้ได้ไหม (กฎข้อ 2-5)
 * @param {object} p
 * @param {object} p.prev  ผลตรวจ NG ครั้งก่อน **ของจุดตรวจเดียวกัน** ({ action_text, inspected_at })
 * @param {object} p.mo    ใบ MO ที่ผูกกับผลตรวจนั้น (null = ไม่มีใบ)
 * @param {object} p.machine แถวทะเบียนเครื่อง (ใช้ `usability` ที่ช่างประกาศ)
 * @returns {{ text:string, from:string, why:string }|null}  `null` = ยกไม่ได้ ต้องพิมพ์เอง
 */
export function carryNgReason({ prev, mo, machine } = {}) {
  const old = txt(prev?.action_text);
  if (!old) return null;                       // ครั้งก่อนก็ไม่มีเหตุผล — ไม่มีอะไรให้ยก
  const use = txt(machine?.usability);
  if (use === 'ok') return null;               // ช่างประกาศแล้วว่าเครื่องใช้ได้ = งานจบ (กฎข้อ 5)
  /* "ใช้ได้ชั่วคราว" = ของยังไม่มา ปัญหายังอยู่ ⇒ ยกต่อ แต่บอกตามจริง (คำสั่ง user 19/11) */
  if (use === 'temp') {
    return { text: old, from: 'temp',
      why: `แก้ไขเบื้องต้นแล้ว รอของมาเปลี่ยน${mo?.mo_no ? ` · MO ${mo.mo_no}` : ''}` };
  }
  if (!moUnresolved(mo)) return null;          // ไม่มีใบ / ใบปิดแล้ว / ซ่อมเสร็จแล้ว = ต้องอธิบายใหม่
  return { text: old, from: 'mo',
    why: `ยกจากการตรวจครั้งก่อน — MO ${mo.mo_no || '(ยังไม่ออกเลข)'} ยังไม่ปิด` };
}

/**
 * ติ๊ก NG แล้วบันทึกได้ไหม (กฎข้อ 1-3)
 * @returns {{ ok:boolean, blockText:string }}
 * 🔴 ของที่ยกมาต้องถูก "ยืนยัน" ก่อน (`accepted`) ไม่ใช่นับว่ามีเหตุผลอัตโนมัติ
 */
export function ngReasonCheck({ attr, text, carry, accepted = false } = {}) {
  if (attr !== 'ng') return { ok: true, blockText: '' };
  if (txt(text)) return { ok: true, blockText: '' };
  if (carry && accepted) return { ok: true, blockText: '' };
  return { ok: false,
    blockText: carry
      ? 'กด "ใช้เหตุผลเดิม" หรือพิมพ์เหตุผลใหม่ก่อน — NG ต้องมีเหตุผลเสมอ'
      : 'ติ๊ก NG ต้องพิมพ์เหตุผลด้วย (กันกดผิดแล้วไม่มีใครรู้)' };
}

/**
 * ติ๊ก OK ทั้งที่ยังมีใบซ่อมค้าง = เตือน (กฎข้อ 6) · `null` = ไม่ต้องเตือน
 * 🔴 **เตือน ไม่บล็อก** — ช่างอาจเพิ่งแก้เสร็จจริงแต่ยังไม่ปิดใบ
 */
export function okWhileMoOpen({ attr, mo, machine } = {}) {
  if (attr !== 'ok') return null;
  if (txt(machine?.usability) === 'ok') return null;   // ช่างประกาศแล้วว่าใช้ได้ = ไม่ต้องเตือน
  if (!moUnresolved(mo)) return null;
  return `จุดนี้ยังมีใบซ่อมค้างอยู่ (MO ${mo.mo_no || '(ยังไม่ออกเลข)'} ยังซ่อมไม่เสร็จ) `
    + 'แต่กะนี้ติ๊ก OK — ถ้าช่างแก้เสร็จแล้วให้ปิดใบด้วย ถ้ายังไม่ได้แก้ควรเป็น NG';
}

export default { carryNgReason, ngReasonCheck, okWhileMoOpen, moUnresolved };
